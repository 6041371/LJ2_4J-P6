      <h2 class="text-2xl font-bold">Wanneer wordt een school Onvoldoende?</h2>
      <p class="text-l ">
        Een school krijgt het eindoordeel Onvoldoende wanneer één van de standaarden
        Resultaten, Zicht op ontwikkeling en begeleiding, Pedagogisch-didactisch handelen
        of Veiligheid Onvoldoende is. Of wanneer twee standaarden binnen de gebieden
        Onderwijsproces en/of Veiligheid en schoolklimaat onvoldoende zijn.
      </p>

      <div class="my-10 px-8 py-6 rounded-xl text-center text-lg font-semibold"
           style="background-color: rgba(151,149,240,0.74);">
        Het oordeel Onvoldoende is daarmee vooral een signaal: hier moet echt iets gebeuren.
      </div>
      

      <h2 class="text-2xl font-bold">Wanneer wordt een school Zeer zwak?</h2>
      <p class="text-l ">
        Zeer zwak is een ander verhaal. Dat oordeel komt niet uit de lucht vallen; het is het resultaat van structurele én langdurige tekortkomingen. Het moment waarop een school Zeer zwak wordt, is het moment waarop zowel de onderwijsresultaten (in het PO kijken we dan naar de resultaten van de doorstroomtoets  over 3 jaar en in het VO naar de vier indicatoren voor onderwijsresultaten) als cruciale onderdelen van het onderwijs onvoldoende zijn, en dat al langere tijd. De combinatie van lage resultaten en onvoldoende onderwijskwaliteit maakt dat het fundament ontbreekt waarop leerlingen kunnen groeien.
Daarom is Zeer zwak geen zwaarder woord voor Onvoldoende, maar een wezenlijk ander signaal: dit raakt aan de kern van wat een school moet bieden. Het bestuur is bij het oordeel Zeer zwak dan ook verplicht de ouders hierover te informeren.
      </p>

   
    <div class="my-10 px-8 py-6 rounded-xl text-center text-lg font-semibold"

      <p class="text-l ">
        En eerlijk is eerlijk: het toezichtstelsel is niet altijd eenvoudig te doorgronden.
        Toch is het cruciaal dat schoolleiders precies weten wat de oordelen betekenen.
        Niet omdat het om labels gaat, maar omdat die oordelen iets zeggen over hoe het gaat met de essentie van het onderwijs:
        de kwaliteit van lesgeven, het leren van leerlingen en de veiligheid in de school. Het verschil tussen ‘Onvoldoende’ en ‘Zeer zwak’ is geen nuanceverschil.
        Het is het verschil tussen een waarschuwingslampje en een alarmbel.

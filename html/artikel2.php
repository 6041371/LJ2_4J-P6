      <h2 class="text-2xl font-bold">Wat de Inspectie eigenlijk beoordeelt</h2>
      <p class="text-l ">
        Achter ieder oordeel gaat een eenvoudig maar scherp kader schuil, gebaseerd op onderwijswetgeving.
        De Inspectie kijkt naar drie kernvragen: krijgen leerlingen goed les, voelen ze zich veilig
        en leren ze voldoende? Deze vragen zijn uitgewerkt in standaarden voor de gebieden
        onderwijsproces, Veiligheid en Onderwijsresultaten. Daar komt één element nog bovenop: of een school weet wat haar kwaliteit is,
        en of zij in staat is om bij te sturen wanneer dat nodig is.
        Dat gaat over sturing, kwaliteitszorg en ambitie – het fundament onder duurzaam goed onderwijs. De beoordeling op deze standaarden vormt samen het eindoordeel op school- of afdelingsniveau:
        Zeer zwak, Onvoldoende of Voldoende.
      </p>


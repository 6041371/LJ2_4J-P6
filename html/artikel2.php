</div>

      <h2 class="text-2xl font-bold">Het (herstel)onderzoek: inspanning alleen is niet genoeg</h2>
      <p class="text-l">
        In gesprekken met schoolleiders merk ik dat er soms een misvatting leeft:
        dat de Inspectie tijdens het herstelonderzoek vooral kijkt naar de inspanning.
        “Als we maar hard gewerkt hebben, dan zien ze dat toch wel?” Maar zo werkt het niet. Er zijn Onvoldoende scholen die zichtbaar alles op alles zetten,
        maar waar de resultaten drie jaar lang onder de norm bleven.
        Bij het herstelonderzoek werd het oordeel dan niet Voldoende, maar juist Zeer zwak. De Inspectie kijkt niet alleen naar wat je hebt gedaan, maar vooral naar wat het heeft opgeleverd.
        Naar het onderwijsleerproces. Naar de kwaliteit van lessen. Naar hoe leerlingen worden begeleid. Naar de resultaten. En naar de sturing op kwaliteit: weet de school waar ze staat, begrijpt ze waarom, en stuurt ze daar effectief op bij?
        Inspanning vertelt iets over betrokkenheid. Resultaat vertelt iets over kwaliteit.
      
      </p>
        <div class="my-10 px-8 py-6 rounded-xl text-center text-lg font-semibold"
           style="background-color: rgba(151,149,240,0.74);">
        Het oordeel doet meestal geen recht aan hoe hard een schoolteam elke dag werkt.</div>
      

      <h2 class="text-2xl font-bold">Hoe voorkom je dat het zover komt?</h2>
      <p class="text-l">
        Het begint met kennis van toezicht en onderwijskwaliteit.
        Wie de spelregels kent, kan bewuster sturen.
        Maar kennis alleen is niet genoeg.
        Scholen die structureel verbeteren, kijken voortdurend naar zichzelf:
        naar trends in data, naar lessen, naar verschillen tussen leerlinggroepen
        en naar de vraag in hoeverre het eigen handelen bijdraagt aan groei of stagnatie.
        Ze analyseren niet alleen wat leerlingen laten zien, maar ook wat leraren laten zien.
        Ze brengen de kwaliteit van lessen systematisch in kaart en bouwen aan een cultuur
        waarin feedback normaal is en analyse voelt als vakmanschap, niet als controle.
        Ze kiezen bewust voor interventies die werken, zoals leerteams,
        gerichte professionalisering of methodieken als Lesson Study –
        niet incidenteel, maar als onderdeel van een doordacht kwaliteitsbeleid.
      </p>

      <h2 class="text-2xl font-bold">Van kennis en inzicht naar verbetering</h2>
      <p class="text-l ">
        ‘Onvoldoende’ en ‘Zeer zwak’ lijken dicht bij elkaar te liggen,
        maar vertegenwoordigen verschillende werkelijkheden.
        Beide zijn alleen goed te duiden wanneer je het onderliggende verhaal begrijpt.
        Wil je meer grip krijgen op waar jouw school of bestuur staat,
        of hoe je gericht kunt sturen op kwaliteit vóórdat het oordeel van buitenaf komt?
        Dan begint het met kennis over toezicht.
</p>


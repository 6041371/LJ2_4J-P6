    </h1>

    <!-- Content -->
    <div class="space-y-6 text-lg leading-relaxed text-800">

      <p class="text-lg">
        Er is een hardnekkige misvatting in het Nederlandse onderwijs: dat je een leerlingpopulatie
        kunt begrijpen door een getal toe te wijzen. De schoolweging was bedoeld als hulpmiddel,
        maar is steeds vaker een lens geworden voor complexiteit.
      </p>

      <p class="text-l ">
        Een getal vangt geen kinderen. Het zegt niets over nieuwsgierigheid, veerkracht,
        motivatie of het pedagogisch-didactisch klimaat waarin leerlingen kunnen opbloeien.
        Het gevaar is subtiel: verwachtingen worden soms aangepast aan cijfers,
        terwijl kansengelijkheid begint bij hoge verwachtingen.
      </p>


      <h2 class="text-2xl font-bold">Een populatie is geen statistiek, maar een verhaal</h2>
      <p class="text-l ">
        Elke school heeft een unieke dynamiek. Niet alleen door de wijk,
        maar ook door gezinnen, thuistalen, ouderbetrokkenheid
        en de manier waarop kinderen leren en groeien.
        Wie die rijkdom wil begrijpen, moet verder kijken dan cijfers.
        Zo ontstaat een levend verhaal waarin een school zichzelf leert kennen.
      </p>


      <!-- Paarse quote -->
      <div class="quote my-10 px-8 py-6 rounded-xl text-center text-lg font-semibold"

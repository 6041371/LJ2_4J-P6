      <h2 class="text-2xl font-bold">Van data naar gezichten: de kracht van persona’s</h2>
      <p class="text-l "> 
        Zonder gezicht blijft populatie-informatie abstract.
        Daarom werk ik graag met persona’s: herkenbare, fictieve leerlingen
        die samen de populatie verbeelden.
        Met persona’  s wordt beleid concreet:
        wat betekent deze keuze voor deze leerling?
        Dat maakt gesprekken scherper en besluiten menselijker.
      </p>

      <p class="text-l ">
        
      </p>


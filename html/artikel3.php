        Ze formuleren visie, aanbod en ondersteuning
        die aansluiten bij de werkelijkheid van hun leerlingen.
        Ze blijven ambitieus, juist wanneer de context complex is.
        Goed onderwijs begint bij begrijpen voor wie je het doet.
      </p>

